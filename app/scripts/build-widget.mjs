// Turns widget/egg-post.html into tgcloud/lib/widgetHtml.js (Serverless modules cannot read files).
import { readFileSync, writeFileSync } from 'node:fs';
import { deflateSync, constants } from 'node:zlib';
const html = readFileSync(new URL('../widget/egg-post.html', import.meta.url), 'utf8');
const packed = deflateSync(Buffer.from(html), { level: constants.Z_BEST_COMPRESSION }).length;
if (packed > 4096) throw new Error(`widget is ${packed} bytes compressed, Telegram allows 4096`);
writeFileSync(new URL('../tgcloud/lib/widgetHtml.js', import.meta.url), `// generated by scripts/build-widget.mjs — do not edit\nexport const EGG_WIDGET_HTML = ${JSON.stringify(html)};\n`);
console.log(`widget: ${Buffer.byteLength(html)} bytes, ${packed} compressed (limit 4096)`);
